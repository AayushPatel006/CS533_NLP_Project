print("4. Initializing the Student Network & Executing Layer Freeze...")
model = AutoModelForSequenceClassification.from_pretrained("distilbert-base-uncased", num_labels=2)

# THE FREEZING PROTOCOL: Lock the core transformer to prevent gradient collapse on small data
for name, param in model.named_parameters():
    if "classifier" not in name and "pre_classifier" not in name:
        param.requires_grad = False

print("   -> Core language layers frozen. Only training the classification head.")

